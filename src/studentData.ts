import { Student, StudentProfile } from './types';

export const getStudentProfile = (student: Student): StudentProfile => ({
  student,
  registrationNumber: student.rollNo,
  nationality: '',
  religion: '',
  community: student.category,
  caste: '',
  motherTongue: '',
  communicationAddress: `${student.district}, ${student.state}`,
  permanentAddress: `${student.district}, ${student.state}`,
  pinCode: '',
  whatsappNumber: '',
  admissionType: '',
  admissionQuota: student.quota,
  firstGraduate: student.firstGenerationGraduate ? 'Yes' : 'No',
  tenthBoard: '',
  tenthSchool: student.schoolType,
  tenthPassingDate: '',
  tenthMedium: '',
  tenthMarks: '',
  twelfthBoard: '',
  twelfthSchool: student.schoolType,
  twelfthPassingDate: '',
  twelfthMedium: '',
  twelfthMarks: `${student.hscMarks}%`,
  subjectMarks: student.recentSubjects.map((subject) => ({
    name: subject.name,
    mark: subject.grade,
  })),
  fatherQualification: '',
  fatherOccupation: '',
  fatherContact: student.guardianPhone,
  motherName: '',
  motherQualification: '',
  motherOccupation: '',
  motherContact: '',
  parentsOccupation: '',
  boardOfStudy: '',
  mediumOfStudy: '',
  familyBackground: '',
  agriculturalLandAvailability: student.agricultureBackground,
  cropsPlanted: '',
  agriculturalLandLocality: '',
  areaOfResidence: '',
  studiedTamilInXii: '',
});
